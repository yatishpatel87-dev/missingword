export const STORAGE_KEYS = {
  TEACHER_SETTINGS: 'mwd_teacher_settings_v1',
  CUSTOM_QUESTIONS: 'mwd_custom_questions_v1',
  GAME_HISTORY: 'mwd_game_history_v1',
  STUDENT_NAME: 'mwd_student_name_v1',
  STUDENT_LEVEL: 'mwd_student_level_v1',
};

export function getStoredQuestions(): Question[] {
  try {
    const raw = localStorage.getItem(STORAGE_KEYS.CUSTOM_QUESTIONS);
    if (!raw) return DEFAULT_QUESTIONS;
    const custom = JSON.parse(raw);
    if (Array.isArray(custom) && custom.length > 0) {
      return [...DEFAULT_QUESTIONS, ...custom];
    }
  } catch (e) {
    console.error('Failed to load custom questions', e);
  }
  return DEFAULT_QUESTIONS;
}

export function getRandomQuestions(level: 1 | 2 | 3, count: number = 20): Question[] {
  const all = getStoredQuestions();
  const filtered = all.filter(q => q.level === level);
  
  // If fewer than requested, fallback to any available
  const pool = filtered.length >= count ? filtered : all;
  
  // Fisher-Yates shuffle
  const shuffled = [...pool];
  for (let i = shuffled.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [shuffled[i], shuffled[j]] = [shuffled[j], shuffled[i]];
  }
  return shuffled.slice(0, count);
}
